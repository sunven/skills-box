        assert_eq!(
            serde_json::to_string(&ErrorCode::EnvNodeMissing).unwrap(),
            "\"env.node_missing\""
        );
        assert!(ErrorCode::EnvNodeMissing.is_env());
        assert!(!ErrorCode::EnvNodeMissing.is_lock());
